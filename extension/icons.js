/**
 * Returns an SVG markup string for `name` (empty string if unknown).
 * `size` is the pixel box; the icon inherits `currentColor`.
 */
function svgIcon(name, size = 14, extraClass = "") {
  const body = SV_ICON_PATHS[name];
  if (!body) return "";
  const cls = extraClass ? ` class="${extraClass}"` : "";
  return (
    `<svg${cls} xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" ` +
    `viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" ` +
    `stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${body}</svg>`
  );
}

/** Returns an SVG element node (for appendChild). */
function svgIconNode(name, size = 14, extraClass = "") {
  const wrap = document.createElement("span");
  wrap.className = "sv-ico" + (extraClass ? " " + extraClass : "");
  wrap.innerHTML = svgIcon(name, size);
  return wrap;
}

/** True if the icon name exists. */
function hasSvgIcon(name) {
  return Object.prototype.hasOwnProperty.call(SV_ICON_PATHS, name);
}
