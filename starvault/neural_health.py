def _sigmoid(x: float) -> float:
    """Numerically stable sigmoid activation function."""
    if x < -45.0:
        return 0.0
    if x > 45.0:
        return 1.0
    return 1.0 / (1.0 + math.exp(-x))


def _leaky_relu(x: float, alpha: float = 0.05) -> float:
    """Leaky ReLU activation function."""
    return x if x > 0 else alpha * x


def _softmax(logits: List[float]) -> List[float]:
    """Numerically stable softmax probability distribution."""
    max_logit = max(logits) if logits else 0.0
    exp_vals = [math.exp(v - max_logit) for v in logits]
    sum_exp = sum(exp_vals) or 1.0
    return [round(v / sum_exp, 4) for v in exp_vals]


def _dot_product(vec_a: List[float], vec_b: List[float]) -> float:
    """Vector dot product."""
    return sum(a * b for a, b in zip(vec_a, vec_b))


def _calculate_shannon_entropy(s: str) -> float:
    """Computes Shannon entropy in bits for character frequency distribution."""
    if not s:
        return 0.0
    freq: Dict[str, int] = {}
    for c in s:
        freq[c] = freq.get(c, 0) + 1
    length = float(len(s))
    entropy = 0.0
    for count in freq.values():
        p = count / length
        entropy -= p * math.log2(p)
    return round(entropy * length, 2)


