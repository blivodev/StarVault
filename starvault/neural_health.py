# Neural Network Inference Engine
# =============================================================================

class VaultSecurityNeuralNet:
    """Zero-knowledge feed-forward neural network for cryptographic vault health classification."""

    def __init__(self) -> None:
        self.w1 = W1
        self.b1 = B1
        self.w2 = W2
        self.b2 = B2
        self.w_risk = W_RISK
        self.b_risk = B_RISK
        self.w_anom = W_ANOMALY
        self.b_anom = B_ANOMALY
        self.w_class = W_CLASS
        self.b_class = B_CLASS
        self.classes = CLASSES

    def extract_features(
        self,
        entry: VaultEntry,
        reuse_map: Optional[Dict[str, int]] = None,
        now: Optional[datetime] = None,
    ) -> List[float]:
        """Extracts 12-dimensional normalized feature vector for a vault entry."""
        vec, _ = extract_entry_features(entry, reuse_map=reuse_map, now=now)
        return vec

    def forward(self, features: List[float]) -> Tuple[float, float, str, Dict[str, float]]:
        """Executes forward pass through the two-layer perceptron.
        
        Returns:
            risk_prob: float (0.0 to 1.0)
            anomaly_prob: float (0.0 to 1.0)
            predicted_class: str
            class_probabilities: Dict[str, float]
        """
        # Hidden Layer 1 (12 -> 16)
        h1 = []
        for i in range(16):
            z = _dot_product(features, self.w1[i]) + self.b1[i]
            h1.append(_leaky_relu(z))

        # Hidden Layer 2 (16 -> 8)
        h2 = []
        for j in range(8):
            z = _dot_product(h1, self.w2[j]) + self.b2[j]
            h2.append(_leaky_relu(z))

        # Output Head 1: Risk Probability
        z_risk = _dot_product(h2, self.w_risk) + self.b_risk
        risk_prob = _sigmoid(z_risk)

        # Output Head 2: Anomaly Probability
        z_anom = _dot_product(h2, self.w_anom) + self.b_anom
        anomaly_prob = _sigmoid(z_anom)

        # Output Head 3: Multi-class Softmax Classification
        logits = []
        for k in range(len(self.classes)):
            z_c = _dot_product(h2, self.w_class[k]) + self.b_class[k]
            logits.append(z_c)

        probs = _softmax(logits)
        class_prob_map = {cls_name: prob for cls_name, prob in zip(self.classes, probs)}
        predicted_class = self.classes[probs.index(max(probs))]

        return risk_prob, anomaly_prob, predicted_class, class_prob_map

    def evaluate_entry(
        self,
        entry: VaultEntry,
        reuse_map: Optional[Dict[str, int]] = None,
        now: Optional[datetime] = None,
    ) -> NeuralEntryAssessment:
        """Evaluates an individual entry through the neural network."""
        features, anomalies = extract_entry_features(entry, reuse_map=reuse_map, now=now)
        risk_prob, anomaly_prob, pred_class, class_probs = self.forward(features)

        # Scale to 0-100 integers
        risk_score = int(round(risk_prob * 100))
        anomaly_score = int(round(anomaly_prob * 100))
        safety_score = max(0, 100 - risk_score)

        # Generate intelligent actionable remediation
        recommendations: List[str] = []
        auto_fix: Optional[str] = None

        if pred_class == "CRITICAL_EXPIRING" or features[5] > 0.4:
            recommendations.append(f"Rotate or renew credential before expiration ({entry.expires_at[:10] if entry.expires_at else 'soon'})")
            auto_fix = "extend_expiry"
        elif pred_class == "REUSED_CREDENTIAL" or features[8] > 0.2:
            recommendations.append("Generate unique high-entropy password to eliminate blast-radius credential reuse")
            auto_fix = "generate_password"
        elif pred_class == "WEAK_ENTROPY" or features[0] < 0.5 or features[1] < 0.5:
            recommendations.append("Upgrade password to 24+ characters with mixed character sets (entropy >= 80 bits)")
            auto_fix = "generate_password"
        elif pred_class == "UNPROTECTED_EXPOSURE" or features[7] < 0.5:
            recommendations.append("Enable TOTP / MFA and restrict privileged access surfaces")
            auto_fix = "enable_totp"
        elif pred_class == "STALE_UNROTATED" or features[4] > 0.5:
            recommendations.append("Perform scheduled lifecycle credential rotation")
            auto_fix = "generate_password"

        # Multi-group & service recommendations
        rec_groups = list(getattr(entry, "groups", []))
        rec_services = list(getattr(entry, "services", []))
        if not rec_groups:
            rec_groups = [entry.category or "Infrastructure"]
        if not rec_services:
            rec_services = [entry.app_name or entry.title]

        return NeuralEntryAssessment(
            entry_id=entry.id,
            entry_title=entry.title,
            entry_type=entry.entry_type,
            risk_score=risk_score,
            anomaly_score=anomaly_score,
            safety_score=safety_score,
            predicted_class=pred_class,
            class_probabilities=class_probs,
            feature_vector=features,
            anomalies=anomalies,
            recommendations=recommendations,
            recommended_groups=rec_groups,
            recommended_services=rec_services,
            auto_fix_action=auto_fix,
        )

    def audit_vault(
        self,
        entries: List[VaultEntry],
    ) -> NeuralVaultAudit:
        """Audits the entire vault collection in-memory using the neural network."""
        start_time = datetime.now(timezone.utc)
        if not entries:
            return NeuralVaultAudit(
                safety_index=100,
                letter_grade="A+",
                total_entries_evaluated=0,
                mean_risk_score=0.0,
                high_risk_entries_count=0,
                anomalies_flagged_count=0,
                entry_assessments=[],
                class_distribution={c: 0 for c in self.classes},
                top_vulnerabilities=[],
                suggested_optimizations=["Vault is currently empty. Add credentials to begin continuous neural protection."],
                execution_time_ms=0.5,
            )

        # Build reuse map
        reuse_map: Dict[str, int] = {}
        for e in entries:
            pwd = e.password or e.api_token
            if pwd:
                reuse_map[pwd] = reuse_map.get(pwd, 0) + 1

        now = datetime.now(timezone.utc)
        assessments: List[NeuralEntryAssessment] = []
        class_dist: Dict[str, int] = {c: 0 for c in self.classes}
        anomalies_total = 0
        high_risk_count = 0

        for e in entries:
            assessment = self.evaluate_entry(e, reuse_map=reuse_map, now=now)
            assessments.append(assessment)
            class_dist[assessment.predicted_class] = class_dist.get(assessment.predicted_class, 0) + 1
            anomalies_total += len(assessment.anomalies)
            if assessment.risk_score >= 65:
                high_risk_count += 1

        # Sort assessments by risk (highest risk first)
        assessments.sort(key=lambda a: (a.risk_score, a.anomaly_score), reverse=True)

        mean_risk = sum(a.risk_score for a in assessments) / float(len(assessments))
        safety_index = max(0, min(100, int(round(100.0 - mean_risk))))

        # Calculate Letter Grade
        if safety_index >= 95:
            letter_grade = "A+"
        elif safety_index >= 85:
            letter_grade = "A"
        elif safety_index >= 75:
            letter_grade = "B"
        elif safety_index >= 65:
            letter_grade = "C"
        elif safety_index >= 50:
            letter_grade = "D"
        else:
            letter_grade = "F"

        # Top vulnerabilities
        top_vulns = []
        for a in assessments[:5]:
            if a.risk_score > 35:
                top_vulns.append({
                    "entry_id": a.entry_id,
                    "title": a.entry_title,
                    "type": a.entry_type,
                    "risk_score": a.risk_score,
                    "predicted_class": a.predicted_class,
                    "anomalies": a.anomalies,
                    "recommendations": a.recommendations,
                })

        # Global optimization suggestions
        opts = []
        if class_dist.get("REUSED_CREDENTIAL", 0) > 0:
            opts.append(f"Eliminate password reuse across {class_dist['REUSED_CREDENTIAL']} entries using the 1-click generator.")
        if class_dist.get("CRITICAL_EXPIRING", 0) > 0:
            opts.append(f"Renew {class_dist['CRITICAL_EXPIRING']} certificates or tokens with upcoming expiration dates.")
        if class_dist.get("WEAK_ENTROPY", 0) > 0:
            opts.append(f"Upgrade {class_dist['WEAK_ENTROPY']} weak credentials to 24+ character high-entropy keys.")
        if class_dist.get("UNPROTECTED_EXPOSURE", 0) > 0:
            opts.append(f"Attach TOTP 2FA to {class_dist['UNPROTECTED_EXPOSURE']} exposed services.")
        if not opts:
            opts.append("Vault security posture is hardened; all neural checks evaluated optimal.")

        end_time = datetime.now(timezone.utc)
        elapsed_ms = round((end_time - start_time).total_seconds() * 1000.0, 2)

        return NeuralVaultAudit(
            safety_index=safety_index,
            letter_grade=letter_grade,
            total_entries_evaluated=len(entries),
            mean_risk_score=round(mean_risk, 1),
            high_risk_entries_count=high_risk_count,
            anomalies_flagged_count=anomalies_total,
            entry_assessments=assessments,
            class_distribution=class_dist,
            top_vulnerabilities=top_vulns,
            suggested_optimizations=opts,
            execution_time_ms=max(0.1, elapsed_ms),
        )


