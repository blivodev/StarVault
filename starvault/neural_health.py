def extract_entry_features(
    entry: VaultEntry,
    reuse_map: Optional[Dict[str, int]] = None,
    now: Optional[datetime] = None,
) -> Tuple[List[float], List[str]]:
    """Transforms a decrypted VaultEntry into a 12-dimensional normalized feature vector.
    
    Zero-Knowledge Guarantee:
    Raw passwords and private keys are never stored or exposed; only statistical
    entropy, length, and non-sensitive structural properties are computed.
    """
    if now is None:
        now = datetime.now(timezone.utc)

    detected_anomalies: List[str] = []
    pwd = entry.password or entry.api_token or ""
    is_keypair = entry.entry_type == "keypair"

    # 1. Normalized Length [0.0 - 1.0]
    # Optimal >= 24 chars, min standard 12
    pwd_len = len(pwd)
    if is_keypair:
        length_norm = 1.0
    else:
        length_norm = min(1.0, pwd_len / 24.0)

    # 2. Normalized Shannon Entropy [0.0 - 1.0]
    # 70+ bits considered strong for passwords, 128+ bits for keys
    if is_keypair:
        entropy_norm = 1.0
    else:
        entropy_bits = _calculate_shannon_entropy(pwd)
        entropy_norm = min(1.0, entropy_bits / 75.0)

    # 3. Character Class Variety [0.0 - 1.0]
    variety_count = 0
    if any(c.islower() for c in pwd): variety_count += 1
    if any(c.isupper() for c in pwd): variety_count += 1
    if any(c.isdigit() for c in pwd): variety_count += 1
    if any(not c.isalnum() for c in pwd): variety_count += 1
    variety_score = variety_count / 4.0 if not is_keypair else 1.0

    # 4. Pattern Cleanliness [0.0 - 1.0] (1.0 = clean, 0.0 = high repetition/predictability)
    pattern_score = 1.0
    if not is_keypair and pwd:
        lower_pwd = pwd.lower()
        # Repetitions
        if re.search(r"(.)\1{2,}", pwd):
            pattern_score -= 0.35
            detected_anomalies.append("Repeated character patterns detected")
        # Common sequential numbers or keyboard walks
        if re.search(r"123|abc|qwerty|asdf|admin|password|letmein|welcome", lower_pwd):
            pattern_score -= 0.50
            detected_anomalies.append("Predictable dictionary or sequence pattern detected")
        # Date or year pattern (e.g. 1999, 2024, 2025)
        if re.search(r"(19|20)\d{2}", pwd):
            pattern_score -= 0.25
            detected_anomalies.append("Contains common calendar year pattern")
        pattern_score = max(0.0, pattern_score)

    # 5. Stale / Age Factor [0.0 - 1.0]
    # > 180 days = 0.6, > 365 days = 1.0
    age_days = 0
    if entry.updated_at or entry.created_at:
        try:
            ts_str = entry.updated_at or entry.created_at
            dt = datetime.fromisoformat(ts_str.replace("Z", "+00:00"))
            if dt.tzinfo is None:
                dt = dt.replace(tzinfo=timezone.utc)
            age_days = max(0, (now - dt).days)
        except Exception:
            age_days = 0
    age_factor = min(1.0, age_days / 365.0)
    if age_days > 365:
        detected_anomalies.append(f"Credential has not been rotated in {age_days} days")

    # 6. Expiry Urgency [0.0 - 1.0]
    # 1.0 = expired, 0.8 = <=7 days, 0.4 = <=30 days, 0.0 = safe
    expiry_urgency = 0.0
    if entry.expires_at:
        try:
            exp_dt = datetime.fromisoformat(entry.expires_at.replace("Z", "+00:00"))
            if exp_dt.tzinfo is None:
                exp_dt = exp_dt.replace(tzinfo=timezone.utc)
            days_left = (exp_dt - now).days
            if days_left < 0:
                expiry_urgency = 1.0
                detected_anomalies.append(f"Expired {abs(days_left)} days ago ({entry.expires_at[:10]})")
            elif days_left <= 7:
                expiry_urgency = 0.85
                detected_anomalies.append(f"Expiring critically soon in {days_left} days")
            elif days_left <= 30:
                expiry_urgency = 0.45
                detected_anomalies.append(f"Expiring in {days_left} days")
        except Exception:
            pass

    # 7. Exposure Surface [0.0 - 1.0]
    # Servers & public APIs have higher attack surface than offline personal keys
    exposure_surface = 0.3
    if entry.entry_type == "server":
        exposure_surface = 0.65
        if entry.username in ("root", "admin", "administrator"):
            exposure_surface += 0.20
            detected_anomalies.append(f"Privileged '{entry.username}' account directly exposed")
        if entry.port in (22, 3389, 80, 443, 8080):
            exposure_surface += 0.10
    elif entry.entry_type == "service":
        exposure_surface = 0.50
        if entry.url and entry.url.startswith("http://"):
            exposure_surface += 0.25
            detected_anomalies.append("Plaintext HTTP protocol in service URI")
    elif entry.entry_type == "apikey":
        exposure_surface = 0.60
        if getattr(entry, "environment", "").lower() == "production":
            exposure_surface += 0.20
    exposure_surface = min(1.0, exposure_surface)

    # 8. MFA / TOTP Protection [0.0 - 1.0] (1.0 = protected)
    has_totp = bool(getattr(entry, "totp_secret", ""))
    mfa_score = 1.0 if has_totp else 0.0
    if not has_totp and entry.entry_type in ("server", "service"):
        detected_anomalies.append("No 2FA / TOTP authentication configured")

    # 9. Reuse Count Normalized [0.0 - 1.0]
    reuse_count = 0
    if reuse_map and pwd:
        reuse_count = reuse_map.get(pwd, 1) - 1
    reuse_score = min(1.0, reuse_count / 4.0)
    if reuse_count > 0:
        detected_anomalies.append(f"Password reused across {reuse_count + 1} distinct vault records")

    # 10. Multi-Group / Organization Breadth [0.0 - 1.0]
    groups = getattr(entry, "groups", []) or []
    services = getattr(entry, "services", []) or []
    real_groups = [g for g in groups if g and g not in ("General", "Uncategorized")]
    group_breadth = 0.0
    if real_groups and services:
        group_breadth = 1.0
    elif real_groups or services:
        group_breadth = 0.6
    elif entry.category and entry.category not in ("General", "Uncategorized"):
        group_breadth = 0.4
    else:
        group_breadth = 0.1
        detected_anomalies.append("Unorganized: missing group and service assignments")

    # 11. Metadata Completeness [0.0 - 1.0]
    meta_count = 0
    if entry.username: meta_count += 1
    if entry.notes: meta_count += 1
    if entry.tags: meta_count += 1
    if getattr(entry, "custom_fields", None): meta_count += 1
    metadata_completeness = min(1.0, meta_count / 3.0)

    # 12. Key Algorithm Strength [0.0 - 1.0]
    key_algorithm_strength = 0.8
    if is_keypair:
        ktype = (getattr(entry, "key_type", "") or "").lower()
        if "ed25519" in ktype or "curve25519" in ktype or "4096" in ktype or "gpg" in ktype:
            key_algorithm_strength = 1.0
        elif "2048" in ktype:
            key_algorithm_strength = 0.6
            detected_anomalies.append("RSA-2048 keypair; upgrade to Ed25519 or RSA-4096 recommended")
        elif "dsa" in ktype or "1024" in ktype:
            key_algorithm_strength = 0.2
            detected_anomalies.append("Deprecated weak key algorithm detected")

    feature_vec = [
        round(length_norm, 4),
        round(entropy_norm, 4),
        round(variety_score, 4),
        round(pattern_score, 4),
        round(age_factor, 4),
        round(expiry_urgency, 4),
        round(exposure_surface, 4),
        round(mfa_score, 4),
        round(reuse_score, 4),
        round(group_breadth, 4),
        round(metadata_completeness, 4),
        round(key_algorithm_strength, 4),
    ]

    return feature_vec, detected_anomalies


