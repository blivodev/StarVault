"""Shared brand-mark loader for the UI.

The mark PNG is generated by `tools/branding/generate_brand.py` so the app
icon, title-bar mark and in-app logo all come from ONE geometry.
"""

from __future__ import annotations

from pathlib import Path
from typing import Optional

import customtkinter as ctk
from PIL import Image

from starvault.config import APP_DIR

_MARK_PATH = Path(__file__).resolve().parent.parent / "resources" / "brand" / "mark.png"

_cache: dict = {}


def mark_image(size: int = 22) -> Optional[ctk.CTkImage]:
    """Returns the StarVault brand mark as a CTkImage at `size` px (or None)."""
    key = ("mark", size)
    if key in _cache:
        return _cache[key]
    try:
        img = Image.open(_MARK_PATH).convert("RGBA")
        img = img.resize((size, size), Image.LANCZOS)
        ck = ctk.CTkImage(light_image=img, dark_image=img, size=(size, size))
        _cache[key] = ck
        return ck
    except Exception:
        _cache[key] = None
        return None
